const assert = require("node:assert/strict");
const { parseTransactionText: parse } = require("./transaction-parser.js");

const actualInput = "週三範例社團\n1200*4=4800\n\n抬頭：範例國小\n統編：12345678\n名稱：115年10月社團鐘點費";
const actual = parse(actualInput, "untaxed");
assert.equal(actual.blocking, false);
assert.equal(actual.fields.buyerName, "範例國小");
assert.equal(actual.fields.buyerTaxId, "12345678");
assert.deepEqual(actual.rows.map(({ name, qty, unit }) => ({ name, qty, unit })), [{ name: "115年10月社團鐘點費", qty: 4, unit: 1200 }]);
assert.deepEqual(actual.contexts, ["週三範例社團"]);
assert.equal(parse(actualInput).priceType, "pending");
assert.equal(parse(actualInput, "taxed").rows[0].priceType, "taxed");

const natural = parse("範例商行，統編12345678，教學4堂，每堂3,000元，教材2,000元，以上未稅。");
assert.equal(natural.blocking, false);
assert.deepEqual(natural.rows.map(({ name, qty, unit }) => ({ name, qty, unit })), [{ name: "教學", qty: 4, unit: 3000 }, { name: "教材", qty: 1, unit: 2000 }]);
assert.equal(natural.priceType, "untaxed");

const labeled = parse("品名：授課費；數量：4；單價：1200；金額：4800；未稅");
assert.equal(labeled.blocking, false);
assert.equal(labeled.rows[0].qty, 4);
assert.equal(parse("抬頭：範例國小 統編：12345678 名稱：社團鐘點費 金額：4800", "untaxed").rows[0].unit, 4800);
assert.equal(parse("名稱：社團鐘點費；總金額：4800元", "untaxed").rows[0].unit, 4800);
assert.equal(parse("名稱：授課費；金額：4800；名稱：教材；金額：2000；總計：6800", "untaxed").rows.length, 2);
assert.equal(parse("名稱：社團鐘點費；1200*4=5000", "untaxed").blocking, true);
assert.equal(parse("名稱：授課費；1200*4=4800；總計：5000", "untaxed").blocking, true);
assert.equal(parse("1200*4=4800").blocking, true);
assert.equal(parse("抬頭：範例國小；統編：12345678").rows.length, 0);
assert.equal(parse("名稱：社團鐘點費；１２００＊４＝４８００；不含稅").rows[0].unit, 1200);
assert.equal(parse("名稱：社團鐘點費；1200*4=4800；含稅又未稅").priceType, "pending");
const merchandise = "客戶名稱：範例國小；統編：12345678；紅色EVO定軸短軸600*20=12000；炫風三培鈴1000*9=9000；小黑炭棍500*10=5000；以上未稅";
for (const input of [merchandise, merchandise.replace(/(紅色EVO定軸短軸|炫風三培鈴|小黑炭棍)/g, "$1；")]) {
  const result = parse(input);
  assert.equal(result.blocking, false);
  assert.equal(result.fields.buyerName, "範例國小");
  assert.deepEqual(result.rows.map(({ name, qty, unit }) => [name, qty, unit]), [["紅色EVO定軸短軸",20,600],["炫風三培鈴",9,1000],["小黑炭棍",10,500]]);
}
assert.equal(parse("名稱：商品A；600*20=12000；名稱：商品B；1000*9=9000；未稅").rows.length, 2);
assert.equal(parse("名稱：115年社團費；1200*4=4800；未稅").rows[0].name, "115年社團費");
assert.equal(parse("小黑炭棍500*10=5500；未稅").blocking, true);
assert.equal(parse("EVO2600*20=52000；未稅").blocking, true);
assert.equal(parse("EVO2：600*20=12000；未稅").rows[0].unit, 600);
assert.equal(parse("30公分炭棍：500*10=5000；未稅").rows[0].name, "30公分炭棍");
assert.equal(parse("學校名稱：範例國小；教學4堂，每堂3000元；未稅").fields.buyerName, "範例國小");
assert.equal(parse("買受人地址：範例路1號；抬頭：範例商行；教材600*20；未稅").fields.buyerAddress, "範例路1號");
assert.equal(parse("教材600*20；未稅").rows[0].qty, 20);
assert.equal(parse("教材20支，每支600元；未稅").rows[0].unit, 600);
assert.equal(parse("名稱：A；金額：4800；名稱：B；金額：2000；未稅").blocking, false);
assert.equal(parse("名稱：教材；單價：600；數量：2；金額：1200；名稱：授課；單價：1000；數量：3；金額：3000；總計：4200；未稅").blocking, false);
const mixed = parse("教學4堂，每堂3000元 未稅；教材1式，每式2100元 含稅");
assert.equal(mixed.blocking, false);
assert.equal(mixed.mixedPricing, true);
assert.deepEqual(mixed.rows.map((row) => row.priceType), ["untaxed", "taxed"]);
assert.deepEqual(parse("教材100元未稅；教材100元含稅").rows.map((row) => row.priceType), ["untaxed", "taxed"]);
assert.deepEqual(parse("品名：教學4堂，每堂3000元 未稅；品名：教材1式，每式2100元 含稅").rows.map((row) => row.priceType), ["untaxed", "taxed"]);
assert.equal(parse("教學4堂，每堂3000元；教材一批；未稅").blocking, true);
assert.match(parse("教學4堂，每堂3000元；教材一批；未稅").issues.join(" "), /教材一批.*缺少金額/);
assert.equal(parse("名稱：教材；教學4堂，每堂3000元；未稅").blocking, true);
assert.equal(parse("教學4堂，每堂3000元").rows[0].priceType, "pending");
console.log("Transaction parser regression checks passed.");
